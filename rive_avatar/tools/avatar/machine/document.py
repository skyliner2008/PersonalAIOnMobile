def patch_default(marker, value):
    for i, ln in enumerate(out):
        if marker in ln:
            out[i] = ln.replace('activeComponentId="0:0"', 'activeComponentId="%s"' % value)
            return
    raise SystemExit("marker not found: " + marker)


